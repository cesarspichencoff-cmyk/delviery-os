function For-Order([string]$date) {
  $dt = [datetime]::ParseExact($date,"yyyy-MM-ddTHH:mm:ss",
    [Globalization.CultureInfo]::InvariantCulture)
  return Read-ServiceState $dt
}
function Has-Code($decision,[string]$code) {
  return @($decision.blockers) -ccontains $code
}
function Check-Block([string]$when,[string]$code,[string]$name) {
  $a = For-Order $when
  Assert-True ((Has-Code $a $code) -and $null -eq $a.service) $name
}
function Check-Allow([string]$when,[string]$service,[string]$name) {
  $a = For-Order $when
  Assert-True ($a.service -ceq $service -and @($a.blockers).Count -eq 0 -and
    $a.evidence -ceq "HUMAN_CONFIRMED_RULE" -and
    $a.source_ref -ceq "LAB_SYNTHETIC:watcher-test") $name
}
