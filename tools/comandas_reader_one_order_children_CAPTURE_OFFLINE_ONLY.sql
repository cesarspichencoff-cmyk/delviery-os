-- ROWSET 5 / OCORRENCIA / referenced notes only, at most 799 accepted
;WITH relevant_occurrences AS (
 SELECT o.CDGRPOCOR,o.CDOCORR FROM TEKNISA.OBSITCOMANDAVEN AS o
 WHERE o.CDFILIAL=:CDFILIAL AND o.NRVENDAREST=:NRVENDAREST AND o.NRCOMANDA=:NRCOMANDA
 UNION
 SELECT o.CDGRPOCOR,o.CDOCORR FROM TEKNISA.OBSITCOMANDAEST AS o
 WHERE o.CDFILIAL=:CDFILIAL AND o.NRVENDAREST=:NRVENDAREST AND o.NRCOMANDA=:NRCOMANDA
)
SELECT TOP (800) c.CDGRPOCOR,c.CDOCORR,c.DSOCORR,c.DSAPELIDOOBS
FROM relevant_occurrences AS r
LEFT JOIN TEKNISA.OCORRENCIA AS c
 ON c.CDGRPOCOR=r.CDGRPOCOR AND c.CDOCORR=r.CDOCORR
ORDER BY r.CDGRPOCOR,r.CDOCORR;

-- ROWSET 6 / PRODUTO / direct, extension and combo-parent codes only, at most 399 accepted
;WITH relevant_product_codes AS (
 SELECT i.CDPRODUTO FROM TEKNISA.ITCOMANDAVEN AS i
 WHERE i.CDFILIAL=:CDFILIAL AND i.NRVENDAREST=:NRVENDAREST AND i.NRCOMANDA=:NRCOMANDA
 UNION
 SELECT i.CDPRODPROMOCAO AS CDPRODUTO FROM TEKNISA.ITCOMANDAVEN AS i
 WHERE i.CDFILIAL=:CDFILIAL AND i.NRVENDAREST=:NRVENDAREST AND i.NRCOMANDA=:NRCOMANDA
  AND i.CDPRODPROMOCAO IS NOT NULL
 UNION
 SELECT e.CDPRODUTO FROM TEKNISA.ITCOMANDAEST AS e
 WHERE e.CDFILIAL=:CDFILIAL AND e.NRVENDAREST=:NRVENDAREST AND e.NRCOMANDA=:NRCOMANDA
)
SELECT TOP (400) p.CDPRODUTO,p.NMPRODUTO
FROM relevant_product_codes AS r
LEFT JOIN TEKNISA.PRODUTO AS p ON p.CDPRODUTO=r.CDPRODUTO
ORDER BY r.CDPRODUTO;