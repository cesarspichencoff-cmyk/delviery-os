-- ROWSET 1 / ITCOMANDAVEN_COMBO / at most 199 accepted
SELECT TOP (200)
 i.CDFILIAL,i.NRVENDAREST,i.NRCOMANDA,i.NRPRODCOMVEN,
 i.CDPRODUTO,i.CDPRODPROMOCAO,i.NRSEQPRODCOM
FROM TEKNISA.ITCOMANDAVEN AS i
WHERE i.CDFILIAL=:CDFILIAL AND i.NRVENDAREST=:NRVENDAREST AND i.NRCOMANDA=:NRCOMANDA
 AND EXISTS (SELECT 1 FROM TEKNISA.COMANDAVEN AS h
 WHERE h.CDFILIAL=i.CDFILIAL AND h.NRVENDAREST=i.NRVENDAREST
  AND h.NRCOMANDA=i.NRCOMANDA AND h.CDLOJA=:CDLOJA AND h.IDORGCMDVENDA='DLV_IFO')
ORDER BY i.NRPRODCOMVEN;

-- ROWSET 2 / ITCOMANDAEST / at most 199 accepted
SELECT TOP (200)
 e.CDFILIAL,e.NRVENDAREST,e.NRCOMANDA,e.NRPRODCOMVEN,
 e.CDPRODUTO,e.QTPROCOMEST
FROM TEKNISA.ITCOMANDAEST AS e
WHERE e.CDFILIAL=:CDFILIAL AND e.NRVENDAREST=:NRVENDAREST AND e.NRCOMANDA=:NRCOMANDA
ORDER BY e.NRPRODCOMVEN,e.CDPRODUTO;

-- ROWSET 3 / OBSITCOMANDAVEN / at most 399 accepted
SELECT TOP (400)
 o.CDFILIAL,o.NRVENDAREST,o.NRCOMANDA,o.NRPRODCOMVEN,
 o.CDGRPOCOR,o.CDOCORR,o.NRPRODCOMVENOBS,o.QTPRODCOMVENOBS
FROM TEKNISA.OBSITCOMANDAVEN AS o
WHERE o.CDFILIAL=:CDFILIAL AND o.NRVENDAREST=:NRVENDAREST AND o.NRCOMANDA=:NRCOMANDA
ORDER BY o.NRPRODCOMVEN,o.CDGRPOCOR,o.CDOCORR;

-- ROWSET 4 / OBSITCOMANDAEST / at most 399 accepted
