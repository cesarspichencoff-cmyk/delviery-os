SET NOCOUNT ON;
SET TRANSACTION ISOLATION LEVEL READ COMMITTED;
SET LOCK_TIMEOUT 2000;
SELECT TOP (32) c.CDFILIAL,c.CDLOJA,c.NRVENDAREST,c.NRCOMANDA,c.IDORGCMDVENDA,v.DTHRABERMESA
FROM TEKNISA.VENDAREST v
JOIN TEKNISA.COMANDAVEN c ON c.CDFILIAL=v.CDFILIAL AND c.NRVENDAREST=v.NRVENDAREST
WHERE v.CDFILIAL='0001' AND c.CDLOJA='01' AND c.IDORGCMDVENDA IN ('DLV_IFO','DLV_NMO')
 AND v.DTHRABERMESA >= @after AND v.DTHRABERMESA <= @until
 AND (v.DTHRABERMESA > @after OR (v.DTHRABERMESA = @after AND
  (c.NRVENDAREST > @sale OR (c.NRVENDAREST = @sale AND c.NRCOMANDA > @order))))
ORDER BY v.DTHRABERMESA,c.NRVENDAREST,c.NRCOMANDA;
