-- Derived from the reviewed six-rowset recipe; READ COMMITTED is NOT a snapshot.
SET NOCOUNT ON;
SET TRANSACTION ISOLATION LEVEL READ COMMITTED;
SET LOCK_TIMEOUT 2000;
BEGIN TRY
SELECT TOP (2) c.CDFILIAL,c.CDLOJA,c.NRVENDAREST,c.NRCOMANDA,c.NRCOMANDAEXT,
 c.IDORGCMDVENDA,c.IDSTCOMANDA,c.DSOBSCOMANDA,v.DTHRABERMESA
FROM TEKNISA.COMANDAVEN c JOIN TEKNISA.VENDAREST v
 ON v.CDFILIAL=c.CDFILIAL AND v.NRVENDAREST=c.NRVENDAREST
WHERE c.CDFILIAL='0001' AND c.CDLOJA='01' AND c.NRVENDAREST=@sale AND c.NRCOMANDA=@order
 AND c.IDORGCMDVENDA IN ('DLV_IFO','DLV_NMO');
SELECT TOP (200) i.CDFILIAL,i.CDLOJA,i.NRVENDAREST,i.NRCOMANDA,
 i.NRPRODCOMVEN,i.CDPRODUTO,p.CDARVPROD,i.QTPRODCOMVEN,i.IDSTPRCOMVEN,
 i.DSOBSDESCIT,i.DSOBSPEDDIGCMD,i.TXPRODCOMVEN
FROM TEKNISA.ITCOMANDAVEN i LEFT JOIN TEKNISA.PRODUTO p ON p.CDPRODUTO=i.CDPRODUTO
WHERE i.CDFILIAL='0001' AND i.CDLOJA='01' AND i.NRVENDAREST=@sale AND i.NRCOMANDA=@order
ORDER BY i.NRPRODCOMVEN;
-- ROWSET 1 / ITCOMANDAVEN_COMBO / at most 199 accepted
SELECT TOP (200)
 i.CDFILIAL,i.NRVENDAREST,i.NRCOMANDA,i.NRPRODCOMVEN,
 i.CDPRODUTO,i.CDPRODPROMOCAO,i.NRSEQPRODCOM
FROM TEKNISA.ITCOMANDAVEN AS i
WHERE i.CDFILIAL='0001' AND i.NRVENDAREST=@sale AND i.NRCOMANDA=@order
 AND EXISTS (SELECT 1 FROM TEKNISA.COMANDAVEN AS h
 WHERE h.CDFILIAL=i.CDFILIAL AND h.NRVENDAREST=i.NRVENDAREST
  AND h.NRCOMANDA=i.NRCOMANDA AND h.CDLOJA='01' AND h.IDORGCMDVENDA IN ('DLV_IFO','DLV_NMO'))
ORDER BY i.NRPRODCOMVEN;

-- ROWSET 2 / ITCOMANDAEST / at most 199 accepted
SELECT TOP (200)
 e.CDFILIAL,e.NRVENDAREST,e.NRCOMANDA,e.NRPRODCOMVEN,
 e.CDPRODUTO,e.QTPROCOMEST
FROM TEKNISA.ITCOMANDAEST AS e
WHERE e.CDFILIAL='0001' AND e.NRVENDAREST=@sale AND e.NRCOMANDA=@order
ORDER BY e.NRPRODCOMVEN,e.CDPRODUTO;

-- ROWSET 3 / OBSITCOMANDAVEN / at most 399 accepted
SELECT TOP (400)
 o.CDFILIAL,o.NRVENDAREST,o.NRCOMANDA,o.NRPRODCOMVEN,
 o.CDGRPOCOR,o.CDOCORR,o.NRPRODCOMVENOBS,o.QTPRODCOMVENOBS
FROM TEKNISA.OBSITCOMANDAVEN AS o
WHERE o.CDFILIAL='0001' AND o.NRVENDAREST=@sale AND o.NRCOMANDA=@order
ORDER BY o.NRPRODCOMVEN,o.CDGRPOCOR,o.CDOCORR;

-- ROWSET 4 / OBSITCOMANDAEST / at most 399 accepted
SELECT TOP (400)
 o.CDFILIAL,o.NRVENDAREST,o.NRCOMANDA,o.NRPRODCOMVEN,
 o.CDPRODUTO,o.CDGRPOCOR,o.CDOCORR
FROM TEKNISA.OBSITCOMANDAEST AS o
WHERE o.CDFILIAL='0001' AND o.NRVENDAREST=@sale AND o.NRCOMANDA=@order
ORDER BY o.NRPRODCOMVEN,o.CDPRODUTO,o.CDGRPOCOR,o.CDOCORR;

-- ROWSET 5 / OCORRENCIA / referenced notes only, at most 799 accepted
;WITH relevant_occurrences AS (
 SELECT o.CDGRPOCOR,o.CDOCORR FROM TEKNISA.OBSITCOMANDAVEN AS o
 WHERE o.CDFILIAL='0001' AND o.NRVENDAREST=@sale AND o.NRCOMANDA=@order
 UNION
 SELECT o.CDGRPOCOR,o.CDOCORR FROM TEKNISA.OBSITCOMANDAEST AS o
 WHERE o.CDFILIAL='0001' AND o.NRVENDAREST=@sale AND o.NRCOMANDA=@order
)
SELECT TOP (800) c.CDGRPOCOR,c.CDOCORR,c.CDPRODUTO,c.DSOCORR,c.DSAPELIDOOBS
FROM relevant_occurrences AS r
LEFT JOIN TEKNISA.OCORRENCIA AS c
 ON c.CDGRPOCOR=r.CDGRPOCOR AND c.CDOCORR=r.CDOCORR
ORDER BY r.CDGRPOCOR,r.CDOCORR;

-- ROWSET 6 / PRODUTO / direct, extension and combo-parent codes only, at most 399 accepted
;WITH relevant_product_codes AS (
 SELECT i.CDPRODUTO FROM TEKNISA.ITCOMANDAVEN AS i
 WHERE i.CDFILIAL='0001' AND i.NRVENDAREST=@sale AND i.NRCOMANDA=@order
 UNION
 SELECT i.CDPRODPROMOCAO AS CDPRODUTO FROM TEKNISA.ITCOMANDAVEN AS i
 WHERE i.CDFILIAL='0001' AND i.NRVENDAREST=@sale AND i.NRCOMANDA=@order
  AND i.CDPRODPROMOCAO IS NOT NULL
 UNION
 SELECT e.CDPRODUTO FROM TEKNISA.ITCOMANDAEST AS e
 WHERE e.CDFILIAL='0001' AND e.NRVENDAREST=@sale AND e.NRCOMANDA=@order
)
SELECT TOP (400) p.CDPRODUTO,p.NMPRODUTO
FROM relevant_product_codes AS r
LEFT JOIN TEKNISA.PRODUTO AS p ON p.CDPRODUTO=r.CDPRODUTO
ORDER BY r.CDPRODUTO;

END TRY
BEGIN CATCH
 THROW;
END CATCH;
